/**
 * Builds the complete list of Category items with numeric 4-digit codes starting from 1001.
 */
export function generateUserCategories(timestamp = Date.now()): Category[] {
  return USER_CATEGORIES_RAW.map((name, index) => {
    const code = (1001 + index).toString();
    return {
      id: `cat-${code}`,
      name,
      code,
      isActive: true,
      sortOrder: index + 1,
      createdAt: timestamp,
      updatedAt: timestamp,
    };
  });
}

/**
 * Builds the complete list of Attribute items with STD (code STD) and numeric 3-digit codes starting from 101.
 */
export function generateUserAttributes(timestamp = Date.now()): Attribute[] {
  const stdAttr: Attribute = {
    id: 'attr-std',
    name: 'STD',
    code: 'STD',
    isActive: true,
    sortOrder: 0,
    createdAt: timestamp,
    updatedAt: timestamp,
  };

  const customAttrs: Attribute[] = USER_ATTRIBUTES_RAW.map((name, index) => {
    const code = (101 + index).toString();
    return {
      id: `attr-${code}`,
      name,
      code,
      isActive: true,
      sortOrder: index + 1,
      createdAt: timestamp,
      updatedAt: timestamp,
    };
  });

  return [stdAttr, ...customAttrs];
}
