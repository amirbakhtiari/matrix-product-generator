// Helper to expand into 1000+ uniquely named items with formatted 4-digit codes
export function generateSeedCharacters(): CharacterDataDef[] {
  const result: CharacterDataDef[] = [];
  const uniqueNames = new Set<string>();

  // Add primary base names first
  for (const name of RAW_CHARACTER_NAMES) {
    const trimmed = name.trim();
    if (!uniqueNames.has(trimmed)) {
      uniqueNames.add(trimmed);
    }
  }

  // Generate thematic variants to reach comfortably 1,000+ rich cartoon character titles
  const prefixes = [
    '',
    'طرح کارتونی ',
    'انیمیشن ',
    'شخصیت محبوب ',
    'تم کودک ',
    'طرح فانتزی ',
  ];

  const suffixes = [
    '',
    ' شاد',
    ' شیطون',
    ' قهرمان',
    ' دوست‌داشتنی',
    ' فانتزی',
    ' کوچولو',
    ' برفی',
    ' فضایی',
    ' ماجراجو',
  ];

  // If initial count is below 1000, systematically create themed editions for apparel
  const baseList = Array.from(uniqueNames);
  let idx = 0;

  // First pass: raw names
  for (const base of baseList) {
    idx++;
    result.push({
      id: `chr-${idx.toString().padStart(4, '0')}`,
      code: idx.toString().padStart(4, '0'),
      name: base,
    });
  }

  // Second pass: thematic combinations until >= 1050 items
  for (const suffix of suffixes) {
    if (!suffix) continue;
    for (const base of baseList) {
      if (result.length >= 1100) break;
      const combined = `${base}${suffix}`;
      if (!uniqueNames.has(combined)) {
        uniqueNames.add(combined);
        idx++;
        result.push({
          id: `chr-${idx.toString().padStart(4, '0')}`,
          code: idx.toString().padStart(4, '0'),
          name: combined,
        });
      }
    }
    if (result.length >= 1100) break;
  }

  return result;
}

export const SEEDED_CHARACTERS_1000: CharacterDataDef[] = generateSeedCharacters();
